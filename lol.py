def parse_line(line):
    # Normalize whitespace to single spaces
    parts = re.split(r'\s+', line.strip())
    if not parts:
        return None
    iin = parts[0]
    # find 'курс' token
    try:
        kurs_idx = parts.index('курс')
    except ValueError:
        # try to find token like 'курс' attached to number e.g., '3' 'курс'
        # if not found, skip
        return None
    # course number just before 'курс'
    course_num = parts[kurs_idx-1] if kurs_idx-1 > 0 else ''
    course = f"{course_num} курс".strip()
    # group is everything after 'курс'
    group = ' '.join(parts[kurs_idx+1:]).strip()
    # email assumed right before course_num
    email = parts[kurs_idx-2] if kurs_idx-2 >= 1 else ''
    # FIO tokens between iin and email
    fio_tokens = parts[1:kurs_idx-2] if (kurs_idx-2) > 1 else []
    # Heuristic split into Last, First, Patronymic
    last_name = fio_tokens[0] if len(fio_tokens) >= 1 else ''
    first_name = fio_tokens[1] if len(fio_tokens) >= 2 else ''
    patronymic = ' '.join(fio_tokens[2:]) if len(fio_tokens) >= 3 else ''
    # pad IIN with leading zero
    iin_padded = iin if iin.startswith('0') else '0' + iin
    password = f"{iin_padded}abc"
    role = "студент"
    return {
        "iin": iin_padded,
        "last_name": last_name,
        "first_name": first_name,
        "patronymic": patronymic,
        "email": email,
        "course": course,
        "group": group,
        "role": role,
        "password": password,
    }

parsed = []
